/* Persona 1 (JP) - reading a Persona off the disc and putting it up.  BTLP only.
 *   0x80085720 BtlSummonActorPersona
 *
 * The fighter's object carries the slot of whoever is acting, and that names
 * the Persona equipped to them; the Persona's record gives the graphics id,
 * and the id indexes the table of sector numbers the pack was built with.
 * The entries are consecutive, so the file's length is the next entry less
 * this one - there is no size field.
 *
 * The read is the same two calls BtlReadSectors makes, written out again
 * rather than called: the wait draws a frame each time round, so whatever is
 * already on screen keeps moving while the Persona loads.
 *
 * The arena is then dimmed to a quarter and the fighter put to full white,
 * both on a one-step fade, so the summon happens against a darkened field.
 */
