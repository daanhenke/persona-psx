/* Where the pack the Personas live in starts. */
extern int D_800F4BAC;

extern short   g_btl_scene_rgb[];
extern short   g_btl_arena_fade;
extern BtlObj *g_btl_persona_obj;

BtlObj *BtlSummonActorPersona(BtlActor *a)
{
    CdlLOC  loc;
    BtlObj *obj;
    int     gfx;

    obj = a->obj;
    gfx = g_btl_personas[BtlActorPersona(obj->mark_num)].key;
    CdIntToPos(g_btl_persona_sectors[gfx] + D_800F4BAC, &loc);
    CdReadFileToAddrAsync((CdlFILE *)&loc,
                          g_btl_persona_sectors[gfx + 1] - g_btl_persona_sectors[gfx],
                          SUMMON_STAGE);
    while (g_cd_busy != -1) {
        BtlDrawFrame();
    }
    obj->rgb_to[0]     = SUMMON_ACTOR_RGB;
    obj->rgb_to[1]     = SUMMON_ACTOR_RGB;
    obj->rgb_to[2]     = SUMMON_ACTOR_RGB;
    g_btl_scene_rgb[0] = SUMMON_SCENE_RGB;
    g_btl_scene_rgb[1] = SUMMON_SCENE_RGB;
    g_btl_scene_rgb[2] = SUMMON_SCENE_RGB;
    obj->fade          = SUMMON_FADE;
    g_btl_arena_fade   = SUMMON_FADE;
    BtlSePlay(SUMMON_BANK, 0);
    g_btl_persona_obj = BtlSpawnPersona(gfx, obj->col2, obj->row, -1);
    BtlObjSetAttr(g_btl_persona_obj, SUMMON_ATTR);
    BtlObjSetScale(g_btl_persona_obj, SUMMON_SCALE_XY, SUMMON_SCALE_XY,
                   SUMMON_SCALE_Z);
    return g_btl_persona_obj;
}
